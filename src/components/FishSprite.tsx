interface Props {
  fish: FishSpecies;
  /** altura em px do sprite renderizado */
  size?: number;
  className?: string;
  /** vira o peixe para a esquerda */
  flip?: boolean;
}

export function FishSprite({ fish, size = 96, className, flip }: Props) {
  const rows = SHAPES[fish.shape];
  const w = rows.reduce((m, r) => Math.max(m, r.length), 0);
  const h = rows.length;

  const pixels: { x: number; y: number; fill: string }[] = [];
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      const c = row[x];
      if (c === '.' || c === ' ') continue;
      const fill = c === '1' ? fish.color : c === '2' ? fish.accent : '#0a0f18';
      pixels.push({ x, y, fill });
    }
  });

  // sombra simples: repete o corpo deslocado, mais escuro
  return (
    <svg
      className={className}
      viewBox={`0 0 ${w} ${h}`}
      width={(size * w) / h}
      height={size}
      shapeRendering="crispEdges"
      style={{ transform: flip ? 'scaleX(-1)' : undefined, maxWidth: '100%' }}
      role="img"
      aria-label={fish.name}
    >
      <g opacity="0.35" transform="translate(0.6,0.6)">
        {pixels.map((p) => (
          <rect key={`s${p.x}-${p.y}`} x={p.x} y={p.y} width={1} height={1} fill="#02121b" />
        ))}
      </g>
      {pixels.map((p) => (
        <rect key={`p${p.x}-${p.y}`} x={p.x} y={p.y} width={1} height={1} fill={p.fill} />
      ))}
    </svg>
  );
}
