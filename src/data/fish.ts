export function fishByRarity(rarity: Rarity, region: RegionId): FishSpecies[] {
  const inRegion = FISH.filter((f) => f.rarity === rarity && f.regions.includes(region));
  return inRegion.length > 0 ? inRegion : FISH.filter((f) => f.rarity === rarity);
}

